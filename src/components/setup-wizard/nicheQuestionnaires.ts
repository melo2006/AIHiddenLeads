/** The questionnaire for a wizard industry name; the generic one when no niche document covers it. */
export function questionnaireForIndustry(industry: string): NicheQuestionnaire {
  const wanted = (industry || "").trim().toLowerCase();
  return NICHE_QUESTIONNAIRES.find((q) => q.industries.some((i) => i.toLowerCase() === wanted)) || GENERIC_QUESTIONNAIRE;
}

/** True when the industry has a dedicated niche questionnaire (not the generic fallback). */
export function hasNicheQuestionnaire(industry: string): boolean {
  return questionnaireForIndustry(industry).key !== GENERIC_QUESTIONNAIRE.key;
}

/** All questions in a questionnaire, in order. */
export function allNicheQuestions(q: NicheQuestionnaire): NicheQuestion[] {
  return q.sections.flatMap((s) => s.questions);
}

